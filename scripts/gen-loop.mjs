// What is generated from the build loop's tools and prompts, so it cannot drift from them (open builder M2-G):
//   skills/build-loop/SKILL.md      from the tool list (mcp/tools/loop.mjs, loop-requests.mjs): names, order, what each does
//   plugin/agents/playtester.md     from the loop's play-test prompt (kits/research/studio-v2/prompts/playtest.md)
// scripts/sync-skills.mjs writes them (and --check fails when one differs); never edit either file by hand.
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ORDER, PLAYTESTER, PROMPTS, tools as loopTools } from '../mcp/tools/loop.mjs';
import { tools as requestTools } from '../mcp/tools/loop-requests.mjs';

const ROOT = path.resolve(fileURLToPath(new URL('../', import.meta.url)));
/** The MCP server's name in every agent's settings (.mcp.json, `gamesfun connect`): a subagent names tools by it. */
export const MCP_SERVER = 'gamesfun';
const GENERATED = 'Generated by scripts/sync-skills.mjs from';
const oneLine = s => String(s).replace(/\s+/g, ' ').trim();
const cell = s => oneLine(s).replace(/\|/g, '\\|');

function args(tool) {
  const req = new Set(tool.inputSchema?.required ?? []);
  const names = Object.keys(tool.inputSchema?.properties ?? {});
  return names.length ? names.map(n => (req.has(n) ? `\`${n}\`` : `\`${n}\` (optional)`)).join(', ') : '(none)';
}

/** skills/build-loop/SKILL.md */
export function buildLoopSkill() {
  const all = [...loopTools, ...requestTools], by = new Map(all.map(t => [t.name, t]));
  const stepTools = [...new Set(ORDER.map(o => o.tool))];
  const other = all.filter(t => !stepTools.includes(t.name));
  for (const o of ORDER) if (!by.has(o.tool)) throw new Error(`gen-loop: the order names ${o.tool}, which is not a tool`);
  return [
    '---',
    'name: build-loop',
    'description: Build a game through the build loop\'s tools (gamesfun_next and the gamesfun_step_* tools) so no step is skipped. Use whenever the gamesfun MCP tools are available and the person wants a game made, changed or finished, or a build has to be picked up after a restart.',
    '---',
    '',
    `<!-- ${GENERATED} mcp/tools/loop.mjs and mcp/tools/loop-requests.mjs. Edit the tools, then run the script. -->`,
    '',
    '# The build loop, through its tools',
    '',
    'The loop that turns an idea into a delivered game is one library (`kits/research/gf-three/loop/`), the same one games.fun\'s Studio runs. Its tools hold the order: each runs one step with the kit\'s own scripts, writes the loop\'s state (`<game>/.gf-loop/state.json`), and answers with the next tool. A tool called out of order is refused, with the reason and the right tool. You never have to remember the order: **call `gamesfun_next` and do what it says.**',
    '',
    '## The order',
    '',
    '| Step | Tool | What happens |',
    '|---|---|---|',
    ...ORDER.map(o => `| ${o.step} | \`${o.tool}\` | ${cell(o.does)} |`),
    '',
    'The loop\'s limits are the library\'s: at most 2 repair rounds for verify and the play-test together, then up to 3 rescue rounds while no version is playable. The person always gets a version, with what still fails named.',
    '',
    '## Your part',
    '',
    '- **An agent round is yours.** The tool that hands it over returns the brief for this game\'s parts. Write `rules.js`, tune `config/*.json`, run `gamesfun_verify` (your own quick check) until it passes, then call `gamesfun_step_fix` with `summary` and `controls`.',
    `- **The play-test is not yours.** \`gamesfun_step_playtest\` returns a message: start the \`${PLAYTESTER}\` subagent with it, do not change the game while it plays, then call the tool again. A report that is older than the game's files is refused.`,
    '- **Proof must be about the files as they are.** Every verify and play-test is recorded with a hash of the game\'s files. Change a file afterwards and delivery is refused until that step has run again.',
    '- **Before each agent round the game is checkpointed.** `gamesfun_rollback` puts the folder back, byte for byte.',
    '- **After a restart,** call `gamesfun_next`: it reads the state file and picks the build up at the right step, with the round\'s brief.',
    '- While the state says `building`, a session with the games.fun plugin is not allowed to stop; `waiting-on-question` and `delivered` let it.',
    '',
    '## Every tool',
    '',
    '| Tool | Arguments | Does |',
    '|---|---|---|',
    ...[...stepTools.map(n => by.get(n)), ...other].map(t => `| \`${t.name}\` | ${args(t)} | ${cell(t.description)} |`),
    '',
  ].join('\n');
}

/** A section of a markdown text by its `## ` heading, without the heading. */
function section(md, heading) {
  const lines = md.split('\n'), i = lines.findIndex(l => l.trim() === `## ${heading}`);
  if (i < 0) throw new Error(`gen-loop: playtest.md has no "## ${heading}" section`);
  const j = lines.findIndex((l, k) => k > i && /^## /.test(l));
  return lines.slice(i + 1, j < 0 ? lines.length : j).join('\n').trim();
}

/** plugin/agents/playtester.md: the play-tester as a subagent of the person's own session. */
export async function playtesterAgent(prompts = PROMPTS) {
  const md = await readFile(path.join(prompts, 'playtest.md'), 'utf8');
  // what the prompt says about who the tester is (before the round note), with the job folder named by the task
  const head = md.split('\n{{ROUND_NOTE}}')[0].split('\n').filter(l => !/^# /.test(l)).join('\n').trim().replaceAll('`{{DIR}}`', 'the folder your task names').replaceAll('{{DIR}}', 'that folder');
  if (head.includes('{{')) throw new Error('gen-loop: the head of playtest.md has a placeholder this script does not fill');
  const tool = n => `mcp__${MCP_SERVER}__${n}`;
  return [
    '---',
    `name: ${PLAYTESTER}`,
    'description: Black-box play-tester for a games.fun game. Plays the game as a new player through the gamesfun_play tool and reports what worked on its own screen. Started by the main session when gamesfun_step_playtest hands the round over, with that tool\'s message as the whole task. Never reads or edits the game\'s code.',
    `tools: Read, ${tool('gamesfun_play')}, ${tool('gamesfun_playtest_report')}`,
    'model: sonnet',
    '---',
    '',
    `<!-- ${GENERATED} kits/research/studio-v2/prompts/playtest.md (the loop's play-test prompt). Edit the prompt in games.fun, sync, then run the script. -->`,
    '',
    head,
    '',
    '## Your task',
    '',
    'Your task names a folder and a file in it, `PLAYTEST.md`: read it first. It is this game\'s brief: the title, the controls, the promises to check, how you play (the `gamesfun_play` tool) and a plan. Follow it, with one difference, because you have no terminal and write no file:',
    '',
    '- The brief says how to report: that tool checks the report and writes the file. Evidence paths are relative to the folder your task names (a run\'s screenshots are under `runs/<name>/`). **Read the image files** of each run before you judge anything.',
    '- You write no other file and run no command: there are no scratch files to keep.',
    '- If the game does not load or play at all, say so in the report: `"verdict": "fail"`, one `feel` entry with `"severity": "blocker"` that says what you saw, and every promise `"pass": null`.',
    '',
    '## Judge',
    '',
    section(md, 'Judge'),
    '',
    'When the report is written, answer with two or three plain sentences: the verdict, what failed and what you could not try.',
    '',
  ].join('\n');
}

/** Every generated file. → [{ file (relative to the kit root), text }] */
export async function generatedFiles() {
  return [
    { file: 'skills/build-loop/SKILL.md', text: buildLoopSkill() },
    { file: 'plugin/agents/playtester.md', text: await playtesterAgent() },
  ];
}

/** → [{ file, same, have }] against the files on disk. */
export async function generatedDrift(root = ROOT) {
  const out = [];
  for (const g of await generatedFiles()) {
    const have = await readFile(path.join(root, ...g.file.split('/')), 'utf8').catch(() => null);
    out.push({ ...g, have, same: have === g.text });
  }
  return out;
}
