#!/usr/bin/env node
// Builds research/gf-three/library/bodies.json: every body on gf-humanoid-1, checked by rig-check, with its size,
// height, tint materials and licence. Static bodies are listed here; generated ones (meshy-character.mjs) leave a
// sidecar library/bodies/<id>.json that is merged in.
//
//   node research/gf-three/tools/lib/char-bodies.mjs [--write]
import './char-node.mjs';
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const here = dirname(fileURLToPath(import.meta.url));
const LIB = resolve(here, '../../library');
const { rigCheck } = await import('../rig-check.mjs');
const { VARIANTS } = await import('../bean.mjs');
const rig = await import('../../kit/character/rig.js');

const GF = { spdx: 'CC0-1.0', author: 'games.fun', url: 'https://games.fun' };
const UAL = { spdx: 'CC0-1.0', author: 'Quaternius', url: 'https://quaternius.itch.io/universal-animation-library',
  source: 'pmndrs/ecctrl@e2cab804f9f15661a642e76f52d09f0b2db63f35 public/AnimationLibrary.glb (sha256 1b7bf678…ee5c)' };
export const STATIC = [
  ...Object.entries(VARIANTS).map(([id, v], i) => ({
    id, label: v.label, file: `bodies/${id}.glb`, from: 'bean', kind: 'bean', default: i === 0,
    tags: ['bean', 'cute', 'toon', 'default'].slice(0, i === 0 ? 4 : 3), color: v.color,
    describe: `procedural ${v.label.toLowerCase()}: one tinted body, mitten hands, shoes, big eyes`,
    license: { ...GF, note: 'generated by research/gf-three/tools/bean.mjs (no third-party art)' },
  })),
  { id: 'ual-mannequin', label: 'Mannequin', file: 'bodies/ual-mannequin.glb', from: 'library', kind: 'cc0', tags: ['mannequin', 'neutral', 'human'],
    describe: 'Quaternius UAL mannequin, the skeleton the clips come from', license: { ...UAL, note: 'renamed onto gf-humanoid-1 by tools/retarget.mjs; materials renamed (tint_main, joints)' } },
  { id: 'quaternius-astronaut', label: 'Astronaut', file: 'bodies/quaternius-astronaut.glb', from: 'library', kind: 'cc0', tags: ['astronaut', 'space', 'sci-fi', 'human'],
    describe: 'Quaternius astronaut in a space suit',
    license: { spdx: 'CC0-1.0', author: 'Quaternius', url: 'https://poly.pizza/m/3hC2i0CTuO',
      source: 'research/foundations/trials/fps-arena/source/assets/models/operative.glb (sha256 c825fb5d…7758, Poly Pizza, retrieved 2026-09-23)',
      note: 'normalised onto gf-humanoid-1 by tools/optimize.mjs --normalize --tint SciFi_Light_Accent; its own clips dropped' } },
  { id: 'quaternius-swat', label: 'SWAT', file: 'bodies/quaternius-swat.glb', from: 'library', kind: 'cc0', tags: ['swat', 'soldier', 'police', 'human'],
    describe: 'Quaternius SWAT officer',
    license: { spdx: 'CC0-1.0', author: 'Quaternius', url: 'https://poly.pizza/m/Btfn3G5Xv4',
      source: 'research/foundations/trials/fps-arena/source/assets/models/swat.glb (sha256 a835107b…fec, Poly Pizza, retrieved 2026-09-23)',
      note: 'normalised onto gf-humanoid-1 by tools/optimize.mjs --normalize --tint Swat --tint-mix 0.4; its own clips dropped' } },
];

export async function buildBodies() {
  const sidecars = readdirSync(join(LIB, 'bodies')).filter(f => f.endsWith('.json') && f !== 'LICENSES.json')
    .map(f => JSON.parse(readFileSync(join(LIB, 'bodies', f), 'utf8')));
  const entries = [...STATIC, ...sidecars.filter(s => !STATIC.some(x => x.id === s.id))];
  const out = [];
  for (const e of entries) {
    const path = join(LIB, e.file);
    if (!existsSync(path)) { console.warn(`skip ${e.id}: ${e.file} missing`); continue; }
    const r = await rigCheck(path);
    const bytes = readFileSync(path);
    const doc = r.stats;
    const tint = [];
    { const { io } = await import('./char-deps.mjs'); const d = await (await io()).read(path); for (const m of d.getRoot().listMaterials()) if (/^tint/i.test(m.getName())) tint.push(m.getName()); }
    out.push({
      ...e,
      rig: rig.RIG,
      height: r.metrics.height, bytes: bytes.length, mb: +(bytes.length / 1e6).toFixed(3), sha256: createHash('sha256').update(bytes).digest('hex'),
      triangles: Math.round(doc.triangles), joints: doc.joints, materials: doc.materials, textures: doc.textures.map(t => t.size?.join('x')).filter(Boolean),
      tint,
      ...(existsSync(join(LIB, 'bodies', `${e.id}.preview.jpg`)) ? { preview: `bodies/${e.id}.preview.jpg` } : {}),
      rigCheck: { ok: r.ok, errors: r.errors, warnings: r.warnings, legScale: r.metrics.legScale, swingDeg: r.metrics.swingDeg },
    });
    console.log(`${r.ok ? 'PASS' : 'FAIL'} ${e.id.padEnd(22)} ${(bytes.length / 1e6).toFixed(2)} MB  ${r.metrics.height} m  ${Math.round(doc.triangles)} tris`);
  }
  return {
    version: 1, rig: rig.RIG, standard: 'research/gf-three/kit/character/RIG.md',
    clips: { file: 'clips/gf-humanoid-1.glb', names: rig.CLIPS, license: { spdx: 'CC0-1.0', author: 'Quaternius (Universal Animation Library); carry, emotes and get-ups authored by games.fun', url: UAL.url, source: UAL.source } },
    default: out.find(b => b.default)?.id ?? out[0]?.id,
    bodies: out,
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const j = await buildBodies();
  if (process.argv.includes('--write')) { writeFileSync(join(LIB, 'bodies.json'), JSON.stringify(j, null, 2) + '\n'); console.log('wrote library/bodies.json'); }
}
