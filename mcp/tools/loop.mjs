/** Where a game's loop keeps its things. The job folder is inside the loop's own folder, so nothing in it is a game file. */
export function places(gameArg) {
  if (typeof gameArg !== 'string' || !gameArg.trim()) throw new Error('game is required: the game folder, e.g. games/my-game');
  const game = path.resolve(KIT_ROOT, gameArg);
  if (game === KIT_ROOT || !/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(path.basename(game))) throw new Error(`${gameArg}: a game folder is named with letters, digits, dashes and dots, e.g. games/my-game`);
  const loop = path.join(game, '.gf-loop'), job = path.join(loop, 'job');
  return {
    game, loop, job, out: path.join(job, 'out'), spec: path.join(job, 'spec.json'), pitch: path.join(job, 'pitch.json'), idea: path.join(job, 'idea.txt'),
    promises: path.join(job, 'promises.json'), playtest: path.join(job, 'playtest'), rounds: path.join(job, 'rounds'), state: stateFileOf(game),
  };
}
