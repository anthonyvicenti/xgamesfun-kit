// one tool at a time on a game (a session may send two calls at once)
const queue = new Map();
function serial(key, fn) {
  const run = (queue.get(key) ?? Promise.resolve()).then(fn, fn);
  queue.set(key, run.catch(() => {}));
  return run;
}

/** A refusal: the order is held here. `code` is stable; `next` is the tool that is right now. */
function refuse(code, why, next = null, extra = {}) {
  return { isError: true, content: [{ type: 'text', text: JSON.stringify({ refused: code, why, ...(next ? { next } : {}), ...extra }, null, 2) }] };
}

