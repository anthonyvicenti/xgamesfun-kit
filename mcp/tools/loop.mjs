// ---------------------------------------------------------------- the hosts (what only this side knows)
/** Is this spec one the kit's create accepts? The check is create's own: it runs into a throwaway folder. → problems[] */
async function specProblems(specFile) {
  const tmp = await mkdtemp(path.join(os.tmpdir(), 'gf-spec-'));
  try { await kitCreate(path.join(tmp, 'game'), { spec: specFile, cwd: KIT_ROOT }); return []; }
  catch (e) { return String(e.message).split('\n').map(l => l.trim()).filter(Boolean).slice(0, 30); }
  finally { await rm(tmp, { recursive: true, force: true }); }
}

/** The answer of a pitch round, as the talk loop's checker reads it: the newer of spec.json and pitch.json. */
async function readAnswer(G) {
  const [st, pt] = await Promise.all([mtime(G.spec), mtime(G.pitch)]);
  if (st == null && pt == null) return { errors: [`no answer yet: write ${p(G.pitch)} (concepts) or ${p(G.spec)} (the locked spec)`], file: null };
  if (st != null && (pt == null || st >= pt)) {
    const errors = await specProblems(G.spec);
    return errors.length ? { errors, file: 'spec.json' } : { file: 'spec.json', value: await readJson(G.spec) };
  }
  const pitch = await readJson(G.pitch);
  if (!pitch) return { errors: ['pitch.json is not JSON'], file: 'pitch.json' };
  const schema = await readJson(PITCH_SCHEMA);
  // each card's spec is held to the spec schema by create's own check, below
  if (schema?.properties?.cards?.items?.properties?.spec) schema.properties.cards.items.properties.spec = { type: 'object' };
  const errors = schemaProblems(schema, pitch).map(e => `pitch ${e}`);
  if (!errors.length) {
    for (const card of pitch.cards ?? []) {
      const tmp = await mkdtemp(path.join(os.tmpdir(), 'gf-card-'));
      try { await writeFile(path.join(tmp, 'spec.json'), JSON.stringify(card.spec)); errors.push(...(await specProblems(path.join(tmp, 'spec.json'))).map(e => `card ${card.id}: ${e}`)); }
      finally { await rm(tmp, { recursive: true, force: true }); }
    }
  }
  return errors.length ? { errors, file: 'pitch.json' } : { file: 'pitch.json', value: pitch };
}

function talkHost(G, { kind, idea = null, resume }) {
  return {
    kind, resume, store: fileStore(G.state),
    firstMessage: pitchMessage(G, { kind, idea }),
    check: () => readAnswer(G),
    repairMessage: errors => `Your answer is not valid yet:\n${errors.slice(0, 20).map(e => `- ${e}`).join('\n')}\n\nFix the file (use only catalog values: \`gamesfun_catalog\`), then call \`gamesfun_step_spec\` {"game": "${p(G.game)}"} again. This is the one repair round.`,
  };
}

async function buildHost(G, { kind = 'build', resume = true, request = null, log = () => {} } = {}) {
  const spec = await readJson(G.spec) ?? await readJson(path.join(G.game, 'spec.json'));
  if (!spec) throw new Error(`no locked spec for ${p(G.game)}: gamesfun_step_spec locks one`);
  const versions = checkpointStore(G.game);
  const specFile = existsSync(G.spec) ? G.spec : path.join(G.game, 'spec.json');
  const tools = {
    ...kitTools({ kit: GF3, cwd: KIT_ROOT, log }),
    // the library's own writePromises reads <job>/game; here the game is not inside the job folder
    promises: async () => {
      try {
        const list = await (await promisesLib(GF3)).promisesFor(G.game, { spec: specFile });
        await mkdir(G.job, { recursive: true });
        await writeFile(G.promises, JSON.stringify(list, null, 2) + '\n');
        return list;
      } catch (e) { log(`  no promise list: ${String(e.message).split('\n')[0].slice(0, 200)}`); return null; }
    },
    ...(seams.tools ?? {}),
  };
  return {
    kind, resume, job: G.job, game: G.game, kit: GF3, who: 'The loop', log,
    paths: { JOB: p(G.job), KIT_TOOLS: p(GF3_TOOLS), PLAYTEST: p(G.playtest) },
    firstMessage: await roundBrief(G, spec, { kind, request }),
    spec, get promises() { try { return JSON.parse(readFileSync(G.promises, 'utf8')); } catch { return null; } },
    tools, versions, prompts: PROMPTS, gameRef: p(G.game),
    hooks: {
      // the create step: the kit's own create (it also writes the game's guide), then the starting game is kept
      async prepare() {
        await mkdir(G.out, { recursive: true });
        if (kind === 'change') return null;
        const made = isGame(G.game), same = made && JSON.stringify(await readJson(path.join(G.game, 'spec.json'))) === JSON.stringify(spec);
        if (!same) {
          try { await kitCreate(G.game, { spec: specFile, force: true, cwd: KIT_ROOT }); }
          catch (e) { return { end: { outcome: 'asked', why: 'create', message: String(e.message).slice(0, 800) } }; }
        }
        if (!same || !await versions.has('created')) await versions.keep('created', { step: 'create' });
        return null;
      },
    },
  };
}

/** Open the build loop on a game as it stands on disk (every tool call does: resume is the normal path). */
async function openBuild(G, options = {}) {
  const lines = [];
  const host = await buildHost(G, { ...options, log: l => lines.push(String(l).trim()) });
  const L = await openBuildLoop(host);
  return { L, host, lines };
}

// ---------------------------------------------------------------- rounds
const roundFile = (G, name) => path.join(G.rounds, `${name}.md`);

/** Hand the next agent round to the session: checkpoint the game first, then take the loop's message. */
async function handOver(L, host, G) {
  const cp = host.versions, n = await cp.next('round'), name = `round-${n}`;
  // a reminder round killed before it was handed: the loop's words need the agent's own verify again
  if (L.state.step === 'agent' && L.state.agent === 'reminder' && !L.mem.own) L.mem.own = await host.tools.ownVerify(G.game) ?? { why: 'no passing verify --quick on record' };
  await cp.keep(name, { step: L.state.step, kind: L.state.step === 'repair' ? L.state.repair : L.state.agent, before: true });
  const r = await L.step();
  if (!r.waiting) return { stepped: r };
  const brief = r.kind === 'build' || r.kind === 'change' ? r.message : inSession(r.message, G);
  await mkdir(G.rounds, { recursive: true });
  await writeFile(roundFile(G, name), brief);
  return { round: { n, checkpoint: name, kind: r.kind, ...(r.model ? { strongerModelAdvised: r.model } : {}), brief } };
}

/** The round that is with the session now (after a kill: read again from the loop's folder). */
async function currentRound(G, s) {
  if (!s?.handed) return null;
  const cp = checkpointStore(G.game);
  if (s.handed.step === 'playtest') {
    const name = `playtest-${s.handed.n}`, m = await cp.get(name);
    return { n: s.handed.n, checkpoint: m ? name : null, kind: 'playtest', agent: PLAYTESTER, brief: await readFile(roundFile(G, name), 'utf8').catch(() => null) };
  }
  if (isTalk(s)) return { kind: s.handed.kind, brief: null };
  const n = await cp.next('round') - 1, name = `round-${n}`;
  return { n, checkpoint: name, kind: s.handed.kind, brief: await readFile(roundFile(G, name), 'utf8').catch(() => null) };
}

/** After a step: hand over the agent round when that is next, then say where the loop stands. */
async function report(L, host, G, said = {}) {
  let round = null;
  if (ROUND_STEPS.includes(L.state.step) && !L.state.handed) {
    const h = await handOver(L, host, G);
    round = h.round ?? null;
  }
  const s = L.state;
  return {
    game: p(G.game), ...said,
    status: s.status, step: s.step, why: s.why,
    ...(round ? { round } : {}),
    ...(s.step === 'done' ? { outcome: s.outcome } : {}),
    next: nextOf(s, G),
  };
}

const outOfOrder = (tool, s, G) => {
  const w = where(s, G);
  return refuse('out-of-order', `${tool} is not the next step. The loop is at "${s ? s.step : 'the start'}"${s?.why ? ` (${s.why})` : ''}. ${w.do}`, w.tool ? { tool: w.tool, args: w.args } : (w.after ?? null), { step: s?.step ?? null, status: s?.status ?? null });
};

/**
 * What the full verify needs before it starts: a browser, and the 3D tools' packages (check 19 reads every body's
 * skeleton). Both are found or installed without writing to this process's stdout, which is the MCP protocol.
 */
async function readyToVerify(ctx) {
  if (seams.tools?.verify) return;
  await ensureBrowser({ log: m => ctx.log?.(m), install: false });
  Object.assign(process.env, TOOL_ENV);
  if (existsSync(path.join(CHAR_DEPS, 'node_modules'))) return;
  const cli = npmCli();
  if (!cli) throw new Error(`the 3D tools need their npm packages. Run: npm ci --prefix "${CHAR_DEPS}"`);
  ctx.progress?.('installing the 3D tools\' packages once (gltf-transform, meshoptimizer, sharp)');
  await new Promise((ok, no) => execFile(process.execPath, [cli, 'ci', '--no-audit', '--no-fund'], { cwd: CHAR_DEPS, windowsHide: true, maxBuffer: 32 << 20 }, e => (e ? no(new Error(`npm ci in ${CHAR_DEPS} failed: ${String(e.message).split('\n')[0]}`)) : ok())));
}

