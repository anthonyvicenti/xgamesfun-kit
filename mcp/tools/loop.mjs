// The build loop as tools (open builder M2-G): a person's own agent session runs games.fun's build loop, and the order
// is held here, not by a prompt. Each tool opens the loop library (kits/research/gf-three/loop, the same one Studio's
// worker calls) on the game folder, runs one step, and answers with the next step and the tool for it. A tool called
// out of order is refused with the reason and the right tool.
//
//   idea → gamesfun_step_pitch → gamesfun_step_spec → gamesfun_step_create → [the session writes the game]
//        → gamesfun_step_fix → gamesfun_step_verify → gamesfun_step_playtest → gamesfun_step_deliver
//
// What is here and what is not:
//   - The steps are the library's (openTalkLoop, openBuildLoop). Nothing here re-implements one: a tool binds the
//     kit's own scripts and folders for a session (the game is games/<name>/, the job folder is inside it at
//     .gf-loop/job/), calls step(), and reports.
//   - The state file <game>/.gf-loop/state.json is written only by the library. The bridge's stop guard and the
//     studio page read it (bridge/CONTRACT.md §5, §6).
//   - An agent round is the session's own work: the tool hands back the brief (composed from the loop's prompt
//     source for this game's parts) and returns. The session calls gamesfun_step_fix when the round is over.
//   - Before each agent round the game folder is checkpointed (lib/checkpoint.mjs); gamesfun_rollback restores one.
//   - No tool starts an agent, calls a model, signs anyone in or holds a credential. The pitch's second reader is a
//     tool round like the play-test: gamesfun_step_spec hands the session one small question per claim, the session
//     puts each to a subagent of its own and returns the answers.
